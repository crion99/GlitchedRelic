using System.Runtime.CompilerServices;
using MegaCrit.Sts2.Core.Map;
using MegaCrit.Sts2.Core.Rooms;
using MegaCrit.Sts2.Core.Runs;
using MegaCrit.Sts2.Core.Runs.History;
using MysteriousMapMod.Generation;

namespace MysteriousMapMod.Map;

internal static class MysteriousMapRules
{
    private sealed class Tag;

    private static readonly ConditionalWeakTable<ActMap, Tag> TaggedMaps = new();
    private static readonly ConditionalWeakTable<MapPoint, Tag> TaggedStartingPoints = new();
    private static readonly ConditionalWeakTable<MapPoint, Tag> TaggedHiddenPoints = new();

    public static void Mark(ActMap map)
    {
        TaggedMaps.GetValue(map, _ => new Tag());
        TaggedStartingPoints.GetValue(map.StartingMapPoint, _ => new Tag());
    }

    public static bool IsActive(ActMap? map)
    {
        if (map == null)
            return false;
        if (map is MysteriousMapActMap || TaggedMaps.TryGetValue(map, out _))
            return true;

        // Concrete ActMap subclasses are not retained by the vanilla save format.
        // Recognize both the nested-map format and legacy grid releases by shape.
        if (map.GetColumnCount() == NestedMapCoordinates.GridSize &&
            map.GetRowCount() == NestedMapCoordinates.GridSize &&
            NestedMapCoordinates.TryDecode(map.StartingMapPoint.coord, out _, out var startRole) &&
            startRole == InnerNodeRole.Entry)
        {
            Mark(map);
            return true;
        }

        var specialCount = 2 + (map.SecondBossMapPoint == null ? 0 : 1);
        var total = map.GetAllMapPoints().Count() + specialCount;
        // Keep recognizing maps generated by earlier releases whose configured
        // room ranges were 17-21, 20-24, and 28-32. Saved maps lose their
        // concrete MysteriousMapActMap subtype, so shape recognition is what
        // preserves exploration rules when those runs are reloaded.
        const int legacyMinNodeCount = 17;
        const int legacyMaxNodeCount = 32;
        var recognizedMaxNodeCount = legacyMaxNodeCount + (map.SecondBossMapPoint == null ? 0 : 1);
        var hasRecognizedNodeCount = total >= legacyMinNodeCount && total <= recognizedMaxNodeCount;
        const int legacyNodeCount = 72;
        const int legacyGridSize = 13;
        if (map.GetColumnCount() != legacyGridSize ||
            map.GetRowCount() != legacyGridSize ||
            (!hasRecognizedNodeCount && total != legacyNodeCount))
        {
            return false;
        }

        if (GetNeighbors(map.StartingMapPoint).Any(p => Manhattan(p.coord, map.StartingMapPoint.coord) != 1))
            return false;

        Mark(map);
        return true;
    }

    public static bool IsStartingPoint(MapPoint point) => TaggedStartingPoints.TryGetValue(point, out _);

    public static void MarkHidden(MapPoint point) =>
        TaggedHiddenPoints.GetValue(point, _ => new Tag());

    // Never infer hidden-room identity from MapPoint.CanBeModified. That is a
    // vanilla working flag and event/map reconstruction is allowed to change it.
    public static bool IsHiddenRoom(MapPoint point) => TaggedHiddenPoints.TryGetValue(point, out _);

    public static bool IsInHiddenNestedRoom(ActMap map, MapPoint point)
    {
        if (!IsNestedMap(map) ||
            !NestedMapCoordinates.TryDecode(point.coord, out var outer, out _))
            return IsHiddenRoom(point);
        var entry = map.GetPoint(NestedMapCoordinates.ToCoord(outer, InnerNodeRole.Entry));
        return entry != null && IsHiddenRoom(entry);
    }

    public static MapPoint? GetNestedRoomEntry(ActMap map, MapPoint point)
    {
        if (!IsNestedMap(map) ||
            !NestedMapCoordinates.TryDecode(point.coord, out var outer, out _))
            return null;
        return map.GetPoint(NestedMapCoordinates.ToCoord(outer, InnerNodeRole.Entry));
    }

    public static IReadOnlyList<MapCoord> GetHiddenRoomCoords(ActMap map) =>
        GetAllPointsIncludingSpecial(map)
            .Where(IsHiddenRoom)
            .Select(point => point.coord)
            .Distinct()
            .Order()
            .ToArray();

    public static void SetHiddenRooms(ActMap map, IEnumerable<MapCoord> hiddenCoords)
    {
        var hidden = hiddenCoords.ToHashSet();
        foreach (var point in GetAllPointsIncludingSpecial(map))
        {
            TaggedHiddenPoints.Remove(point);
            // MysteriousMap topology and assigned room types are immutable.
            // Normalizing this vanilla flag also repairs polluted old saves.
            point.CanBeModified = false;
            if (hidden.Contains(point.coord))
                MarkHidden(point);
        }
    }

    public static IEnumerable<MapPoint> GetNeighbors(MapPoint point)
    {
        // Edges are stored once as a rooted tree. Unioning parents and children
        // gives the undirected, four-direction room connectivity.
        return point.parents.Concat(point.Children).Distinct();
    }

    public static HashSet<MapCoord> GetExplored(RunState runState) => runState.VisitedMapCoords.ToHashSet();

    public static bool IsRepeatableShopPoint(RunState runState, MapPoint point)
    {
        if (IsNestedMap(runState.Map))
            return false;
        if (point.PointType == MapPointType.Shop)
            return true;
        if (point.PointType != MapPointType.Unknown ||
            runState.CurrentActIndex < 0 ||
            runState.CurrentActIndex >= runState.MapPointHistory.Count)
        {
            return false;
        }

        return HasResolvedShopHistory(
            point.coord,
            runState.VisitedMapCoords,
            runState.MapPointHistory[runState.CurrentActIndex]);
    }

    internal static bool HasResolvedShopHistory(
        MapCoord coord,
        IReadOnlyList<MapCoord> visits,
        IReadOnlyList<MapPointHistoryEntry> history)
    {
        // EnterMapCoord appends a repeated coordinate before the new history
        // entry is created. Only inspect the paired prefix so a question-mark
        // shop remains recognizable during that transition window.
        for (var index = Math.Min(visits.Count, history.Count) - 1; index >= 0; index--)
        {
            if (visits[index] == coord && history[index].HasRoomOfType(RoomType.Shop))
                return true;
        }
        return false;
    }

    public static bool IsFrontier(RunState runState, MapPoint point)
    {
        if (IsNestedMap(runState.Map))
            return CanEnter(runState, point.coord, debugTravel: false);

        var explored = GetExplored(runState);
        return !explored.Contains(point.coord) &&
               (!IsHiddenRoom(point) || HiddenRoomState.IsRevealed(runState, point)) &&
               GetNeighbors(point).Any(n => explored.Contains(n.coord));
    }

    public static IEnumerable<MapPoint> GetAllPointsIncludingSpecial(ActMap map)
    {
        yield return map.StartingMapPoint;
        foreach (var point in map.GetAllMapPoints())
            yield return point;
        yield return map.BossMapPoint;
        if (map.SecondBossMapPoint != null)
            yield return map.SecondBossMapPoint;
    }

    public static Dictionary<MapCoord, int> ComputeDistances(ActMap map)
    {
        var result = new Dictionary<MapCoord, int> { [map.StartingMapPoint.coord] = 0 };
        var queue = new Queue<MapPoint>();
        queue.Enqueue(map.StartingMapPoint);
        while (queue.Count > 0)
        {
            var point = queue.Dequeue();
            foreach (var neighbor in GetNeighbors(point).OrderBy(p => p.coord))
            {
                if (result.TryAdd(neighbor.coord, result[point.coord] + 1))
                    queue.Enqueue(neighbor);
            }
        }
        return result;
    }

    public static bool CanEnter(RunState runState, MapCoord destination, bool debugTravel)
    {
        if (!IsActive(runState.Map))
            return true;
        if (debugTravel)
            return runState.Map.HasPoint(destination);

        var point = runState.Map.GetPoint(destination);
        if (point == null)
            return false;

        if (IsNestedMap(runState.Map))
            return CanEnterNested(runState, point);

        var explored = GetExplored(runState);
        if (explored.Count == 0)
            return destination == runState.Map.StartingMapPoint.coord;

        // Vanilla double-boss rewards return to the map after boss one. Preserve
        // that contract and make boss two the only legal next destination.
        if (runState.Map.SecondBossMapPoint != null && explored.Contains(runState.Map.BossMapPoint.coord))
            return destination == runState.Map.SecondBossMapPoint.coord && !explored.Contains(destination);

        // A shop may be revisited after leaving it, but selecting the shop that
        // is already the active room would attempt to re-enter itself.
        if (runState.CurrentRoom is MegaCrit.Sts2.Core.Rooms.MerchantRoom &&
            runState.CurrentMapCoord == destination)
        {
            return false;
        }

        if (explored.Contains(destination))
            return IsRepeatableShopPoint(runState, point);

        if (IsHiddenRoom(point) && !HiddenRoomState.IsRevealed(runState, point))
            return false;

        if (point == runState.Map.SecondBossMapPoint)
            return false;

        return GetNeighbors(point).Any(n => explored.Contains(n.coord));
    }

    public static bool IsNestedMap(ActMap? map) =>
        map != null && map.GetColumnCount() == NestedMapCoordinates.GridSize &&
        map.GetRowCount() == NestedMapCoordinates.GridSize;

    public static bool IsNestedExit(MapPoint point) =>
        NestedMapCoordinates.TryDecode(point.coord, out _, out var role) && role == InnerNodeRole.Exit;

    public static bool IsNestedEntry(MapPoint point) =>
        NestedMapCoordinates.TryDecode(point.coord, out _, out var role) && role == InnerNodeRole.Entry;

    private static bool CanEnterNested(RunState runState, MapPoint destination)
    {
        var visits = runState.VisitedMapCoords;
        if (visits.Count == 0)
            return destination == runState.Map.StartingMapPoint;

        var current = runState.Map.GetPoint(visits[^1]);
        if (current == null)
            return false;

        // Double-boss acts retain the game's normal forced second-boss step.
        if (runState.Map.SecondBossMapPoint != null && current == runState.Map.BossMapPoint)
            return destination == runState.Map.SecondBossMapPoint;

        if (!IsNestedExit(current))
            return !visits.Contains(destination.coord) && current.Children.Contains(destination);

        if (!NestedMapCoordinates.TryDecode(current.coord, out var currentOuter, out _) ||
            !NestedMapCoordinates.TryDecode(destination.coord, out var destinationOuter, out var destinationRole) ||
            Manhattan(currentOuter, destinationOuter) != 1)
        {
            return false;
        }

        if (destinationRole == InnerNodeRole.Entry)
        {
            if (visits.Contains(destination.coord))
                return false;
            return !IsHiddenRoom(destination) || HiddenRoomState.IsRevealed(runState, destination);
        }

        // Selecting an adjacent cleared room's exit acts as fast traversal
        // through that room without replaying its route or rewards.
        return destinationRole == InnerNodeRole.Exit && visits.Contains(destination.coord);
    }

    public static int FindLatestVisitIndex(RunState runState, MapCoord coord)
    {
        for (var i = runState.VisitedMapCoords.Count - 1; i >= 0; i--)
        {
            if (runState.VisitedMapCoords[i] == coord)
                return i;
        }
        return -1;
    }

    private static int Manhattan(MapCoord a, MapCoord b) => Math.Abs(a.col - b.col) + Math.Abs(a.row - b.row);

    private static int Manhattan(GridCell a, GridCell b) => Math.Abs(a.Col - b.Col) + Math.Abs(a.Row - b.Row);
}
